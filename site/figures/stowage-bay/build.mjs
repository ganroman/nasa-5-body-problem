const kitCss = readFileSync(join(HERE, "..", "kit", "iso.css"), "utf8");
function topLevelRules(source) {
  const rules = [];
  let depth = 0;
  let from = 0;
  source.split("").forEach((char, at) => {
    if (char === "{") depth++;
    if (char === "}" && --depth === 0) {
      rules.push(source.slice(from, at + 1).trim());
      from = at + 1;
    }
  });
  return rules;
}
const kept = (rule) => /^(\.iso|@keyframes iso-|@media)/.test(rule) && !/^\.iso-(figure|legend|keys?|key|swatch|caption)/.test(rule) && !rule.includes(".iso-swatch");
