"""Load and validate the curated seed YAML in backend/seed/.

Validation only: nothing here touches the database. Field names mirror app.models so the
DB loader can map rows directly.
"""

import re
from pathlib import Path
from typing import Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field, model_validator

from app.enums import (
    Dimension,
    EnvDomain,
    EnvMaturity,
    FindingTopic,
    GravityRegime,
    Hazard,
    MatchConfidence,
    Origin,
    Provenance,
    ReviewStatus,
    RouteStatus,
    SourceKind,
    TestMethod,
    UseState,
    ValueStatus,
)

# PSI investigation sources are generated by a separate ingest, so seed files may cite them
# before they exist in sources.yaml.
PSI_SOURCE_ID = re.compile(r"^psi-\d+-[a-z0-9-]+$")

# Absolute bounds per internal unit; anything outside is a transcription error.
DIMENSION_BOUNDS: dict[Dimension, tuple[float, float | None]] = {
    Dimension.o2_fraction: (0, 1),
    Dimension.co2_fraction: (0, 1),
    Dimension.n2_fraction: (0, 1),
    Dimension.pressure_kpa: (0, None),
    Dimension.airflow_ms: (0, None),
    Dimension.temperature_c: (-273.15, None),
    Dimension.relative_humidity_pct: (0, 100),
}


class Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


class SourceSeed(Strict):
    id: str = Field(max_length=80)
    kind: SourceKind
    title: str
    doi: str | None = None
    url: str | None = None
    publisher: str | None = None
    revision: str | None = None
    published_on: str | None = None
    accessed_on: str | None = None
    access_notes: str | None = None


class ConditionSeed(Strict):
    value_min: float | None = None
    value_max: float | None = None
    status: ValueStatus
    source_id: str | None = None
    locator: str | None = None
    note: str | None = None

    @model_validator(mode="after")
    def _check(self) -> "ConditionSeed":
        no_value = self.value_min is None and self.value_max is None
        if (self.status == ValueStatus.unknown) != no_value:
            raise ValueError("status 'unknown' if and only if value_min and value_max are both null")
        if self.value_min is not None and self.value_max is not None and self.value_min > self.value_max:
            raise ValueError("value_min > value_max")
        return self


class EnvironmentSeed(Strict):
    id: str = Field(max_length=60)
    name: str
    domain: EnvDomain
    gravity_regime: GravityRegime
    gravity_g: float | None = None
    maturity: EnvMaturity
    summary: str | None = None
    source_id: str | None = None
    doc_path: str | None = None
    conditions: dict[str, dict[Dimension, ConditionSeed]]

    @model_validator(mode="after")
    def _check(self) -> "EnvironmentSeed":
        for space, dims in self.conditions.items():
            missing = set(Dimension) - set(dims)
            if missing:
                # Every dimension is written out so a gap is an explicit unknown, not an omission.
                raise ValueError(f"{self.id}/{space}: missing dimensions {sorted(missing)}")
            for dim, c in dims.items():
                lo, hi = DIMENSION_BOUNDS[dim]
                for v in (c.value_min, c.value_max):
                    if v is not None and (v < lo or (hi is not None and v > hi)):
                        raise ValueError(f"{self.id}/{space}/{dim}: {v} outside [{lo}, {hi}]")
        return self


class RouteSeed(Strict):
    id: str = Field(pattern=r"^R\d{2}$")
    from_env: str
    to_env: str
    status: RouteStatus
    prototype_status: Literal["operating", "reference", "illustrative"]
    cargo_types: list[str]
    possible_cargo: str | None = None
    description: str | None = None
    source_ids: list[str] = Field(min_length=1)


class MaterialSeed(Strict):
    id: str = Field(max_length=80)
    canonical_name: str
    material_class: str | None = None
    formulation: str | None = None
    form: str | None = None
    thickness_m: float | None = Field(default=None, gt=0)
    notes: str | None = None


class PassedOutcome(Strict):
    passed: bool


class LoiOutcome(Strict):
    loi_fraction: float = Field(gt=0, le=1)


class MaterialTestSeed(Strict):
    material_id: str
    test_method: TestMethod
    o2_fraction: float | None = Field(default=None, ge=0, le=1)
    pressure_kpa: float | None = Field(default=None, gt=0)
    o2_raw: str | None = None
    pressure_raw: str | None = None
    outcome: PassedOutcome | LoiOutcome
    gravity_regime: GravityRegime
    source_id: str
    locator: str
    note: str | None = None

    @model_validator(mode="after")
    def _check(self) -> "MaterialTestSeed":
        if self.test_method == TestMethod.astm_d2863:
            if not isinstance(self.outcome, LoiOutcome):
                raise ValueError("astm_d2863 needs outcome {loi_fraction: x}")
        elif self.test_method in (TestMethod.std6001_test1, TestMethod.std6001_test4):
            if not isinstance(self.outcome, PassedOutcome):
                raise ValueError(f"{self.test_method} needs outcome {{passed: bool}}")
            if self.o2_fraction is None or self.pressure_kpa is None:
                raise ValueError(f"{self.test_method} result needs o2_fraction and pressure_kpa")
        return self


class ComponentSeed(Strict):
    name: str
    original_label: str
    material_id: str | None
    identity_confidence: MatchConfidence
    mass_share: float | None = Field(default=None, ge=0, le=1)

    @model_validator(mode="after")
    def _check(self) -> "ComponentSeed":
        if (self.identity_confidence == MatchConfidence.unmatched) != (self.material_id is None):
            raise ValueError("identity_confidence 'unmatched' if and only if material_id is null")
        return self


class CargoConfigSeed(Strict):
    version: int = Field(ge=1)
    assembly_notes: str | None = None
    supported_use_states: list[UseState] = []
    components: list[ComponentSeed] = Field(min_length=1)


class CargoSeed(Strict):
    slug: str = Field(max_length=80)
    name: str
    purpose: str | None = None
    provenance: Provenance
    origin: Origin
    config: CargoConfigSeed


class FindingSeed(Strict):
    id: str = Field(max_length=80)
    claim: str
    excerpt: str
    locator: str
    source_id: str
    hazard: Hazard
    topic: FindingTopic
    applies_o2_min: float | None = Field(default=None, ge=0, le=1)
    applies_o2_max: float | None = Field(default=None, ge=0, le=1)
    applies_pressure_kpa_min: float | None = Field(default=None, ge=0)
    applies_pressure_kpa_max: float | None = Field(default=None, ge=0)
    applies_airflow_ms_min: float | None = Field(default=None, ge=0)
    applies_airflow_ms_max: float | None = Field(default=None, ge=0)
    applies_gravity_regime: GravityRegime | None = None
    limits: str
    review_status: ReviewStatus = ReviewStatus.draft
    reviewed_by: str | None = None
    material_ids: list[str] = []


class ReferencePassageSeed(Strict):
    id: str = Field(max_length=80)
    source_id: str
    passage: str
    locator: str
    hazard: Hazard | None = None
    scope: str
    relevance: str | None = None
    unresolved_applicability: str | None = None
    review_status: ReviewStatus = ReviewStatus.draft


class Seed(Strict):
    sources: list[SourceSeed]
    environments: list[EnvironmentSeed]
    routes: list[RouteSeed]
    materials: list[MaterialSeed]
    material_tests: list[MaterialTestSeed]
    cargo: list[CargoSeed]
    findings: list[FindingSeed]
    reference_passages: list[ReferencePassageSeed]


def _read(seed_dir: Path, name: str) -> list:
    # A file with only comments (or "[]") is an intentionally empty table.
    return yaml.safe_load((seed_dir / f"{name}.yaml").read_text(encoding="utf-8")) or []


def _unique(kind: str, ids: list[str]) -> set[str]:
    seen: set[str] = set()
    dupes = {i for i in ids if i in seen or seen.add(i)}
    if dupes:
        raise ValueError(f"duplicate {kind} ids: {sorted(dupes)}")
    return seen


def _cross_check(seed: Seed) -> None:
    source_ids = _unique("source", [s.id for s in seed.sources])
    env_ids = _unique("environment", [e.id for e in seed.environments])
    material_ids = _unique("material", [m.id for m in seed.materials])
    _unique("route", [r.id for r in seed.routes])
    _unique("cargo", [c.slug for c in seed.cargo])
    _unique("finding", [f.id for f in seed.findings])
    _unique("reference passage", [p.id for p in seed.reference_passages])
    _unique("material test locator", [f"{t.source_id}#{t.locator}" for t in seed.material_tests])

    errors: list[str] = []

    def src(where: str, sid: str | None) -> None:
        if sid is not None and sid not in source_ids and not PSI_SOURCE_ID.match(sid):
            errors.append(f"{where}: unknown source_id {sid!r}")

    def mat(where: str, mid: str | None) -> None:
        if mid is not None and mid not in material_ids:
            errors.append(f"{where}: unknown material_id {mid!r}")

    for e in seed.environments:
        src(f"environment {e.id}", e.source_id)
        for space, dims in e.conditions.items():
            for dim, c in dims.items():
                src(f"environment {e.id}/{space}/{dim}", c.source_id)
    for r in seed.routes:
        for end in (r.from_env, r.to_env):
            if end not in env_ids:
                errors.append(f"route {r.id}: unknown environment {end!r}")
        for sid in r.source_ids:
            src(f"route {r.id}", sid)
    for i, t in enumerate(seed.material_tests):
        mat(f"material_test #{i}", t.material_id)
        src(f"material_test #{i}", t.source_id)
    for c in seed.cargo:
        for comp in c.config.components:
            mat(f"cargo {c.slug}/{comp.name}", comp.material_id)
    for f in seed.findings:
        src(f"finding {f.id}", f.source_id)
        for mid in f.material_ids:
            mat(f"finding {f.id}", mid)
    for p in seed.reference_passages:
        src(f"reference passage {p.id}", p.source_id)

    if errors:
        raise ValueError("seed cross-reference errors:\n  " + "\n  ".join(errors))


def load_seed(seed_dir: Path) -> Seed:
    """Parse every seed file, validate each row, then check references between files."""
    seed = Seed(**{name: _read(seed_dir, name) for name in Seed.model_fields})
    _cross_check(seed)
    return seed
