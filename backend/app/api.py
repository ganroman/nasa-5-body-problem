@router.get("/environments")
def list_environments(session: Session = Depends(get_session)) -> list[dict[str, Any]]:
    envs = session.scalars(select(Environment).options(selectinload(Environment.conditions)).order_by(Environment.id))
    return [_environment(e) for e in envs]


@router.get("/environments/{env_id}")
def get_environment(env_id: str, session: Session = Depends(get_session)) -> dict[str, Any]:
    env = session.get(Environment, env_id)
    if env is None:
        raise HTTPException(404, f"environment '{env_id}' not found")
    return _environment(env)


def _environment(e: Environment) -> dict[str, Any]:
    spaces: dict[str, dict[str, Any]] = {}
    for c in e.conditions:
        spaces.setdefault(c.space, {})[c.dimension] = {
            "min": sc._plain(c.value_min), "max": sc._plain(c.value_max), "status": c.status,
            "source_id": c.source_id, "locator": c.locator, "note": c.note,
        }
    return {
        "id": e.id, "name": e.name, "domain": e.domain, "gravity_regime": e.gravity_regime,
        "gravity_g": sc._plain(e.gravity_g), "maturity": e.maturity, "summary": e.summary,
        "source_id": e.source_id, "doc_path": e.doc_path, "spaces": spaces,
    }


