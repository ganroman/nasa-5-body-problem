@router.post("/scenarios/compare")
def compare(body: CompareIn, session: Session = Depends(get_session)) -> dict[str, Any]:
    cargo = _resolve_cargo(session, body)
    return {"cargo": cargo, **_or_404(sc.compute, session, cargo, body.scenario.model_dump())}


@router.post("/scenarios/explain")
def explain(body: ExplainIn, session: Session = Depends(get_session)) -> dict[str, Any]:
    cargo = _resolve_cargo(session, body)
    if body.component_index >= len(cargo["components"]):
        raise HTTPException(422, "component_index out of range")
    result = _or_404(sc.compute, session, cargo, body.scenario.model_dump())
    inputs = sc.si_inputs(result, cargo, body.component_index, body.hazard, body.question)
    # Tools only for follow-up questions: the default summary stays one provider request (rate limit).
    tools = sc.si_tools(session, result, cargo, body.component_index) if body.question else None
    explanation = explain_cached(session, inputs, tools=tools)
    return {"explanation": explanation, "sources": inputs["sources"] + explanation.get("tool_records", []),
            "disclosure": SI_DISCLOSURE}


@router.post("/passports/export")
def export_passport(body: ExportIn, session: Session = Depends(get_session)) -> dict[str, Any]:
    cargo = _resolve_cargo(session, body)
    result = _or_404(sc.compute, session, cargo, body.scenario.model_dump())
    share = session.get(Share, body.share_slug) if body.share_slug else None
    if body.share_slug and share is None:
        raise HTTPException(404, f"share '{body.share_slug}' not found")
    snapshot = {
        "passport_version": 1,
        "generated_at": datetime.now(UTC).isoformat(),
        "cargo": cargo,
        "scenario": body.scenario.model_dump(mode="json"),
        **result,
        "observations": {str(k): v for k, v in result["observations"].items()},
        "si_disclosure": SI_DISCLOSURE,
    }
    export = PassportExport(
        snapshot=jsonable_encoder(snapshot), si_disclosure=SI_DISCLOSURE,
        share_slug=share.slug if share else None, scenario_id=share.scenario_id if share else None,
    )
    session.add(export)
    session.commit()
    return {"id": str(export.id), "passport": export.snapshot}


@router.get("/passports/{export_id}")
def get_passport(export_id: str, session: Session = Depends(get_session)) -> dict[str, Any]:
    try:
        export = session.get(PassportExport, uuid.UUID(export_id))
    except ValueError:
        export = None
    if export is None:
        raise HTTPException(404, "passport not found")
    return {"id": str(export.id), "passport": export.snapshot}


