def _resolve_cargo(session: Session, body: CompareIn) -> dict[str, Any]:
    if body.cargo_slug:
        return _or_404(sc.seeded_cargo, session, body.cargo_slug)
    _check_materials(session, body.cargo)
    return {**body.cargo.model_dump(), "provenance": Provenance.illustrative, "origin": Origin.user}


def _check_materials(session: Session, cargo: CargoIn) -> None:
    ids = {c.material_id for c in cargo.components if c.material_id}
    known = set(session.scalars(select(Material.id).where(Material.id.in_(ids)))) if ids else set()
    if missing := ids - known:
        raise HTTPException(422, f"unknown material_id: {sorted(missing)}")


def _or_404(fn, *args):
    try:
        return fn(*args)
    except sc.NotFound as e:
        raise HTTPException(404, str(e)) from e


def _hash_token(token: str) -> str:
    # Tokens are 192-bit random, so a plain SHA-256 is enough (no password-style KDF needed).
    return hashlib.sha256(token.encode()).hexdigest()


def _save_cargo_and_scenario(session: Session, item: CargoItem, body: ShareIn) -> tuple[CargoConfig, Scenario]:
    """New config version + scenario; earlier versions are kept so conclusions never carry over."""
    version = max((c.version for c in item.configs), default=0) + 1
    config = CargoConfig(
        item=item, version=version, assembly_notes=body.cargo.assembly_notes,
        components=[Component(position=i, **c.model_dump()) for i, c in enumerate(body.cargo.components)],
    )
    session.add(config)
    s = body.scenario
    suggested = _or_404(sc.suggested_conditions, session, s.environment_id, s.space)
    if not suggested:
        raise HTTPException(404, f"environment '{s.environment_id}' has no space '{s.space}'")
    session.flush()
    scen = Scenario(
        config_id=config.id, environment_id=s.environment_id, space=s.space, route_id=s.route_id, use_state=s.use_state,
        conditions=[
            ScenarioCondition(
                dimension=r["dimension"], suggested_min=r["suggested_min"], suggested_max=r["suggested_max"],
                suggested_status=r["suggested_status"], suggested_source_id=r["suggested_source_id"],
                override_value=s.overrides.get(r["dimension"]),
            )
            for r in suggested
        ],
    )
    session.add(scen)
    session.flush()
    return config, scen


def _share_payload(session: Session, share: Share) -> dict[str, Any]:
    config = session.get(CargoConfig, share.cargo_config_id)
    scen = session.get(Scenario, share.scenario_id) if share.scenario_id else None
    cargo = sc.cargo_from_config(config.item, config)
    return {
        "slug": share.slug,
        "updated_at": share.updated_at,
        "cargo": {k: cargo[k] for k in ("name", "purpose", "assembly_notes", "components")},
        "config_version": config.version,
        "scenario": None if scen is None else {
            "environment_id": scen.environment_id, "space": scen.space, "use_state": scen.use_state,
            "route_id": scen.route_id,
            "overrides": {c.dimension: float(c.override_value) for c in scen.conditions if c.override_value is not None},
        },
    }


