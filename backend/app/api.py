SHARES_PER_IP_PER_HOUR = 20


def _ip_hash(request: Request) -> str:
    # First X-Forwarded-For hop is the client behind Vercel's proxy. Keyed with a server secret so
    # stored hashes cannot be reversed by hashing all IPv4 addresses.
    ip = (request.headers.get("x-forwarded-for") or "").split(",")[0].strip() or (request.client.host if request.client else "")
    return hmac.new(get_settings().database_url.encode(), ip.encode(), hashlib.sha256).hexdigest()


@router.post("/shares", status_code=201)
def create_share(body: ShareIn, request: Request, session: Session = Depends(get_session)) -> dict[str, Any]:
    ip_hash = _ip_hash(request)
    recent = session.scalar(select(func.count()).select_from(Share).where(
        Share.creator_ip_hash == ip_hash, Share.created_at > datetime.now(UTC) - timedelta(hours=1)))
    if recent >= SHARES_PER_IP_PER_HOUR:
        raise HTTPException(429, f"share limit reached ({SHARES_PER_IP_PER_HOUR} per hour); try again later")
    _check_materials(session, body.cargo)
    forked = None
    if body.forked_from_slug:
        forked = session.scalar(select(CargoItem).where(CargoItem.slug == body.forked_from_slug))
        if forked is None:
            raise HTTPException(404, f"cargo '{body.forked_from_slug}' not found")
    item = CargoItem(name=body.cargo.name, purpose=body.cargo.purpose, provenance=Provenance.illustrative,
                     origin=Origin.user, forked_from_id=forked.id if forked else None)
    session.add(item)
    config, scen = _save_cargo_and_scenario(session, item, body)
    token = secrets.token_urlsafe(24)
    share = Share(slug=secrets.token_urlsafe(9), edit_token_hash=_hash_token(token),
                  cargo_config_id=config.id, scenario_id=scen.id, creator_ip_hash=ip_hash)
    session.add(share)
    session.commit()
    # The edit token is returned once; only its hash is stored.
    return {**_share_payload(session, share), "edit_token": token}


@router.get("/shares/{slug}")
def get_share(slug: str, session: Session = Depends(get_session)) -> dict[str, Any]:
    share = session.get(Share, slug)
    if share is None:
        raise HTTPException(404, "share not found")
    return _share_payload(session, share)


@router.put("/shares/{slug}")
def update_share(slug: str, body: ShareIn, x_edit_token: str = Header(), session: Session = Depends(get_session)) -> dict[str, Any]:
    share = session.get(Share, slug)
    if share is None:
        raise HTTPException(404, "share not found")
    if not hmac.compare_digest(share.edit_token_hash, _hash_token(x_edit_token)):
        raise HTTPException(403, "invalid edit token")
    _check_materials(session, body.cargo)
    item = session.get(CargoConfig, share.cargo_config_id).item
    item.name, item.purpose = body.cargo.name, body.cargo.purpose
    config, scen = _save_cargo_and_scenario(session, item, body)
    share.cargo_config_id, share.scenario_id = config.id, scen.id
    session.commit()
    return _share_payload(session, share)
