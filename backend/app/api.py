class ComponentIn(BaseModel):
    name: str = Field(min_length=1, max_length=120)
    original_label: str = Field(min_length=1, max_length=300)
    material_id: str | None = Field(default=None, max_length=80)
    identity_confidence: MatchConfidence = MatchConfidence.unmatched
    mass_share: float | None = Field(default=None, ge=0, le=1)

    @model_validator(mode="after")
    def _identity(self) -> "ComponentIn":
        if (self.material_id is None) != (self.identity_confidence == MatchConfidence.unmatched):
            raise ValueError("material_id must be null exactly when identity_confidence is 'unmatched'")
        return self


class CargoIn(BaseModel):
    name: str = Field(min_length=1, max_length=120)
    purpose: str | None = Field(default=None, max_length=500)
    assembly_notes: str | None = Field(default=None, max_length=2000)
    components: list[ComponentIn] = Field(min_length=1, max_length=30)


class ScenarioIn(BaseModel):
    environment_id: str = Field(max_length=60)
    space: str = Field(default="cabin", max_length=40)
    use_state: UseState
    route_id: str | None = Field(default=None, max_length=8)
    overrides: dict[Dimension, float] = {}

    @model_validator(mode="after")
    def _bounds(self) -> "ScenarioIn":
        for dim, v in self.overrides.items():
            lo, hi = sc.DIMENSION_BOUNDS[dim]
            if not lo <= v <= hi:
                raise ValueError(f"{dim} override {v} outside {lo}..{hi} (internal units)")
        return self


class CompareIn(BaseModel):
    """Either a seeded `cargo_slug` or an inline `cargo`."""

    cargo_slug: str | None = Field(default=None, max_length=80)
    cargo: CargoIn | None = None
    scenario: ScenarioIn

    @model_validator(mode="after")
    def _one_cargo(self) -> "CompareIn":
        if (self.cargo_slug is None) == (self.cargo is None):
            raise ValueError("give exactly one of cargo_slug or cargo")
        return self


class ExplainIn(CompareIn):
    component_index: int = Field(ge=0)
    hazard: Hazard = Hazard.fire
    question: str | None = Field(default=None, max_length=500)


class ShareIn(BaseModel):
    cargo: CargoIn
    scenario: ScenarioIn
    forked_from_slug: str | None = Field(default=None, max_length=80)


class ExportIn(CompareIn):
    share_slug: str | None = Field(default=None, max_length=32)


